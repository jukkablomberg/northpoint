#!/usr/bin/env node
/**
 * scripts/gen-provenance.mjs — [NP-SKILL-OUTPUT-PROVENANCE]
 *
 * WHY.
 * The audit a pack produces is the one artefact that leaves the user's machine
 * (to counsel, an agency, a founder) and it carried no trace of what produced
 * it. Every pack with an `## Output format` section now ends its output with
 * one provenance line, and its JSON renderings carry a `provenance` object:
 *
 *   PROVENANCE: <pack> v<version> · <N> rules · MIT · northpoint.fi/skills/<page>?ref=audit-output · run <ISO date>
 *
 * Every field except the run date is DERIVED here, never typed:
 *   - pack name + rule count: readPacks() in gen-citation.mjs (the H1, else the
 *     description) — the same reading CITATION.cff and the README are checked
 *     against; where the pack also declares "## The N rules", the two must agree.
 *   - version: the pack's own frontmatter `metadata.version`. A pack that
 *     states none renders "unversioned" — a version is never invented here.
 *   - licence: frontmatter `license`.
 *   - URL: the pack's northpoint.fi/skills/<page> page when one exists (PAGES
 *     below; the site repo's tests/skill-provenance.test.mjs asserts PAGES
 *     equals the page registry in scripts/gen-skill-pages.mjs), else the
 *     /skills index — said out loud in the --check output.
 *
 * The block sits between markers at the end of the `## Output format`
 * section. It is written only by this script. A hand edit inside the markers,
 * or a PROVENANCE line typed anywhere outside them, is RED in --check, naming
 * the pack — drift is a test, not a review.
 *
 * The block never adds a field to a structured-output tool call: `submit_audit`
 * carries only what its schema defines (the site repo's
 * tests/skill-pack-output-contract.test.mjs guards that contract).
 *
 * USAGE
 *   node scripts/gen-provenance.mjs            rewrite the blocks in place
 *   node scripts/gen-provenance.mjs --check    exit 1 if any block is missing or differs
 *   node scripts/gen-provenance.mjs --json     print the derived fields
 *
 * Run it after editing any SKILL.md frontmatter, H1 or rule count; then
 * `node scripts/gen-citation.mjs`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readPacks } from './gen-citation.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = path.join(REPO, 'skills');

/* pack dir -> the /skills/<page> route on northpoint.fi. Asserted equal to the
   site's page registry (gen-skill-pages.mjs REGISTRY) by the site test suite. */
export const PAGES = Object.freeze({
  'mica-marketing-self-audit-pro': 'mica',
  'vara-marketing-self-audit-pro': 'vara',
  'mas-marketing-self-audit-pro': 'mas',
  'ad-creative-compliance-pro': 'ad-creative',
  'gdpr-marketing-self-audit-pro': 'gdpr',
  'tge-launch-readiness-pro': 'tge',
  'fca-financial-promotions-pro': 'fca',
  'sec-retail-communications-pro': 'sec',
  'aeo-visibility-audit-pro': 'aeo',
});

export const REF = 'audit-output';
export const BEGIN = '<!-- provenance:begin — generated by scripts/gen-provenance.mjs from this pack\'s frontmatter and rule count; do not edit by hand -->';
export const END = '<!-- provenance:end -->';
const OUTPUT_HEAD = /^## Output format.*$/m;
const DECLARED = /^## The (\d+) rules\s*$/m;

export function metadataVersion(md) {
  const fm = (md.match(/^---\n([\s\S]*?)\n---/) || [, ''])[1];
  const meta = fm.split(/^metadata:\s*$/m)[1];
  if (!meta) return null;
  const v = meta.match(/^[ \t]+version:[ \t]*["']?([^"'\s]+)["']?[ \t]*$/m);
  return v ? v[1] : null;
}

/** The fields for one pack, or { error }. */
export function deriveProvenance(pack, md) {
  if (pack.rules === null) return { error: `${pack.slug}: has an Output format section but states no rule count of its own` };
  const d = md.match(DECLARED);
  if (d && Number(d[1]) !== pack.rules) {
    return { error: `${pack.slug}: H1/description says ${pack.rules} rules but "## The ${d[1]} rules" says ${d[1]}` };
  }
  const page = PAGES[pack.slug] || null;
  return {
    slug: pack.slug,
    pack: pack.title,
    version: metadataVersion(md),
    rules: pack.rules,
    license: pack.license || 'MIT',
    page,
    url: `northpoint.fi/skills${page ? '/' + page : ''}?ref=${REF}`,
  };
}

export function provenanceLine(p, run = '{run date, YYYY-MM-DD}') {
  const v = p.version ? `v${p.version}` : 'unversioned';
  return `PROVENANCE: ${p.pack} ${v} · ${p.rules} rules · ${p.license} · ${p.url} · run ${run}`;
}

export function renderBlock(p) {
  const obj = {
    pack: p.pack,
    version: p.version,
    rules: p.rules,
    license: p.license,
    url: 'https://' + p.url,
    run: '{run date, YYYY-MM-DD}',
  };
  return [
    BEGIN,
    '**Provenance.** End the report with this one line, verbatim except the run',
    'date (the date of this run, ISO 8601):',
    '',
    '```',
    provenanceLine(p),
    '```',
    '',
    'Any JSON rendering of this audit (an audit-history row, or the JSON above)',
    'carries one more top-level key, `provenance`, with the same fields:',
    '',
    '```json',
    '"provenance": ' + JSON.stringify(obj),
    '```',
    '',
    'A structured-output tool call (`submit_audit`) carries only the fields its',
    'schema defines — never add `provenance` to it.',
    END,
  ].join('\n');
}

/** Returns the new file text: any existing block removed, the fresh one at the end of the Output format section. */
export function applyBlock(md, block) {
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  let text = md.replace(new RegExp('\\n*' + esc(BEGIN) + '[\\s\\S]*?' + esc(END) + '\\n*', 'g'), '\n\n');
  const h = text.match(OUTPUT_HEAD);
  if (!h) return null;
  const start = h.index + h[0].length;
  const rest = text.slice(start);
  const nxt = rest.match(/^## (?!#)/m);
  let end = start + (nxt ? nxt.index : rest.length);
  let section = text.slice(start, end);
  // Keep a trailing `---` separator after the block.
  const sep = section.match(/\n---\s*$/);
  const cut = sep ? start + sep.index : end;
  const before = text.slice(0, cut).replace(/\s+$/, '');
  const after = text.slice(cut).replace(/^\s+/, '');
  if (after === '') return before + '\n\n' + block + '\n';
  return before + '\n\n' + block + '\n\n' + after;
}

/** -> { results: [{slug, file, want, have, fields}], problems: [] } */
export function plan(skillsDir = SKILLS) {
  const problems = [];
  const results = [];
  const packs = readPacks(skillsDir);
  for (const pack of packs) {
    const file = path.join(skillsDir, pack.slug, 'SKILL.md');
    const md = fs.readFileSync(file, 'utf8');
    const hasSection = OUTPUT_HEAD.test(md);
    // A PROVENANCE line outside the markers is a typed line — never allowed.
    const outside = md.replace(/<!-- provenance:begin[\s\S]*?<!-- provenance:end -->/g, '');
    if (/PROVENANCE:/.test(outside)) problems.push(`${pack.slug}: a PROVENANCE line is typed outside the generated block`);
    if (!hasSection) {
      if (md.includes('provenance:begin')) problems.push(`${pack.slug}: carries a provenance block but has no Output format section`);
      results.push({ slug: pack.slug, skipped: 'no Output format section' });
      continue;
    }
    const f = deriveProvenance(pack, md);
    if (f.error) { problems.push(f.error); continue; }
    const want = applyBlock(md, renderBlock(f));
    results.push({ slug: pack.slug, file, have: md, want, fields: f });
  }
  return { results, problems };
}

function check(skillsDir) {
  const { results, problems } = plan(skillsDir);
  for (const r of results) {
    if (r.skipped) continue;
    if (!r.have.includes(BEGIN)) problems.push(`${r.slug}: no provenance block — run \`node scripts/gen-provenance.mjs\``);
    else if (r.have !== r.want) {
      const got = (r.have.match(/^PROVENANCE: .*$/m) || ['<none>'])[0];
      problems.push(`${r.slug}: provenance block disagrees with the pack's own frontmatter/rule count (has ${JSON.stringify(got)}, derived ${JSON.stringify(provenanceLine(r.fields))}) — run \`node scripts/gen-provenance.mjs\``);
    }
  }
  const skipped = results.filter((r) => r.skipped).map((r) => r.slug);
  const indexOnly = results.filter((r) => r.fields && !r.fields.page).map((r) => r.slug);
  if (skipped.length) console.log(`note: ${skipped.join(', ')} have no Output format section — no provenance line.`);
  if (indexOnly.length) console.log(`note: ${indexOnly.join(', ')} have no /skills/<page>; their line points at northpoint.fi/skills?ref=${REF}.`);
  if (problems.length) {
    console.error('gen-provenance --check FAILED:');
    for (const p of problems) console.error('  - ' + p);
    return 1;
  }
  console.log(`gen-provenance --check ok — ${results.length - skipped.length} packs carry a provenance block derived from their own frontmatter.`);
  return 0;
}

export function main(argv = process.argv.slice(2)) {
  const i = argv.indexOf('--skills');
  const dir = i >= 0 ? argv[i + 1] : SKILLS;
  if (argv.includes('--check')) return check(dir);
  const { results, problems } = plan(dir);
  if (argv.includes('--json')) {
    console.log(JSON.stringify(results.map((r) => r.fields || r), null, 2));
    return problems.length ? 1 : 0;
  }
  if (problems.length) {
    console.error('gen-provenance refused:');
    for (const p of problems) console.error('  - ' + p);
    return 1;
  }
  let n = 0;
  for (const r of results) {
    if (r.skipped || r.have === r.want) continue;
    fs.writeFileSync(r.file, r.want); n++;
  }
  console.log(`gen-provenance: ${n} pack(s) rewritten, ${results.filter((r) => !r.skipped).length} carry the block.`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) process.exit(main());
